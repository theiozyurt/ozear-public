import { spawn, spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root=fileURLToPath(new URL('../',import.meta.url));
process.chdir(root);
const [major, minor] = process.versions.node.split('.').map(Number);
if (major < 22 || (major === 22 && minor < 13))throw new Error('Node.js 22.13 veya daha yeni bir sürüm gerekli.');
function run(args,env={}){const result=spawnSync(process.execPath,args,{cwd:root,stdio:'inherit',env:{...process.env,...env}});if(result.error)throw result.error;if(result.status!==0)process.exit(result.status??1);}
if(!existsSync('node_modules/vinext/dist/cli.js')){
  console.log('Ozear bağımlılıkları kuruluyor…');
  run(['scripts/install-ci.mjs']);
}
console.log('Tipler ve MCP sözleşmeleri kontrol ediliyor…');
run(['node_modules/typescript/bin/tsc','--noEmit','-p','tsconfig.check.json']);
run(['tests/contracts.mjs']);
console.log('Uygulama derleniyor…');
run(['scripts/run-framework.mjs','build']);
// This ignored, local build configuration is regenerated by the next build.
const configPath='dist/server/wrangler.json';
const config=JSON.parse(readFileSync(configPath,'utf8'));
const binding=config.d1_databases?.find(database=>database.binding==='DB');
if(!binding)throw new Error('DB veritabanı bağlantısı derleme çıktısında bulunamadı.');
binding.migrations_dir=path.resolve(root,'drizzle');
writeFileSync(configPath,JSON.stringify(config,null,2)+'\n');
console.log('Yerel veritabanı hazırlanıyor…');
run(['--import','./scripts/sites-env.mjs','./node_modules/wrangler/bin/wrangler.js','d1','migrations','apply','DB','--local','--config',configPath,'--persist-to','.wrangler/state'],{CI:'true'});
if(process.argv.includes('--prepare-only')){console.log('Ozear hazır. Başlatmak için npm run dev çalıştır.');process.exit(0);}
console.log('\nOzear başlatılıyor. Yerel giriş adresi: http://127.0.0.1:5173/signin-with-chatgpt?return_to=/\n');
const server=spawn(process.execPath,['scripts/run-framework.mjs','dev'],{cwd:root,stdio:'inherit'});
process.on('SIGINT',()=>server.kill('SIGINT'));
process.on('SIGTERM',()=>server.kill('SIGTERM'));
server.on('exit',code=>process.exit(code??0));
